// Tree tab: comment inside a node, expand shows it; a task node also shows its settings (about 10 s)
const {chromium}=require('playwright');
const {open,sleep,checks,shot,state,noSideScroll}=require('./harness');
const t=checks();
(async()=>{const br=await chromium.launch();const {p:a,errs}=await open(br,{w:1280,h:860});
  try{
    const pid=await a.evaluate(()=>document.querySelector('[data-pgo]').dataset.pgo);
    await a.evaluate(i=>document.querySelector(`[data-pgo="${i}"]`).click(),pid);await sleep(300);
    await a.click('[data-ptab=tree]');await sleep(150);
    await a.click('[data-trroot]');await sleep(150);await a.keyboard.type('Launch');await a.keyboard.press('Tab');await sleep(150);await a.keyboard.type('Design');
    await a.click('.tr-bar');await sleep(200);
    let s=await state(a),N=s.projects.find(x=>x.id===pid).tree;const L=N.find(x=>x.name==='Launch'),D=N.find(x=>x.name==='Design');
    await a.hover(`[data-tn="${L.id}"]`);await a.click(`[data-tn="${L.id}"] [data-trexp]`);await sleep(200);
    t.is('expand opens a comment box',!!await a.$(`[data-tn="${L.id}"] .trn-panel .trn-cmt`));
    t.is('plan node shows no task settings',!await a.$(`[data-tn="${L.id}"] .trn-panel .trn-set`));
    await a.keyboard.type('Talk to Ana first\nthen the budget');await a.click('.tr-bar');await sleep(250);
    s=await state(a);t.is('comment saved on the node',s.projects.find(x=>x.id===pid).tree.find(x=>x.id===L.id).comment==='Talk to Ana first\nthen the budget');
    t.is('comment icon is marked when a node has one',await a.evaluate(i=>document.querySelector(`[data-tn="${i}"] .tr-exp`).classList.contains('has'),L.id));
    await a.click(`[data-tn="${L.id}"] [data-trexp]`);await sleep(200);
    t.is('closing hides the comment',!await a.$('.trn-panel'));
    t.is('the guides still lay out',await a.evaluate(()=>!!document.querySelector('.tr-canvas')));
    await a.hover(`[data-tn="${L.id}"]`);await a.click(`[data-tn="${L.id}"] [data-trtask]`);await sleep(200);
    s=await state(a);const lt=s.tasks.find(x=>x.id===s.projects.find(y=>y.id===pid).tree.find(y=>y.id===L.id).taskId);
    t.is('→ Task carries the comment into the task note',lt&&lt.note==='Talk to Ana first\nthen the budget');
    await a.click(`[data-tn="${L.id}"] [data-trexp]`);await sleep(200);
    t.is('task node shows the comment and its settings',await a.evaluate(i=>{const p=document.querySelector(`[data-tn="${i}"] .trn-panel`);return !!p&&p.querySelector('.trn-cmt').value.startsWith('Talk to Ana')&&/Status/.test(p.querySelector('.trn-set').textContent)&&!!p.querySelector('[data-tredit]')},L.id));
    await shot(a,'tree-notes');
    await a.click(`[data-tn="${L.id}"] .trn-panel [data-tredit]`);await sleep(250);
    t.is('Edit task opens the edit window',!!await a.$('#ed-name'));
    await a.keyboard.press('Escape');await sleep(200);
    await a.hover(`[data-tn="${L.id}"]`);await a.click(`[data-tn="${L.id}"] [data-trunlink]`);await sleep(250);
    s=await state(a);t.is('Plan only keeps the comment on the node',s.projects.find(x=>x.id===pid).tree.find(x=>x.id===L.id).comment.startsWith('Talk to Ana'));
    await a.click(`[data-tn="${D.id}"] [data-trpdone]`);await sleep(250);
    s=await state(a);t.is('a plan node can be ticked done',s.projects.find(x=>x.id===pid).tree.find(x=>x.id===D.id).done===true);
    t.is('done node stays in the tree, ticked',await a.evaluate(i=>{const d=document.querySelector(`[data-tn="${i}"]`);return !!d&&d.classList.contains('done')&&d.querySelector('[data-trpdone]').checked},D.id));
    await shot(a,'tree-node-done');
    await a.click('[data-pback]');await sleep(200);await a.click('[data-view=done]');await sleep(250);
    t.is('Done tab has a tree section with the node and its project',await a.evaluate(()=>{const r=document.querySelector('.tnd-sec .tnd-row');return !!r&&/Design/.test(r.textContent)&&/Research/.test(r.textContent)}));
    await shot(a,'tree-done-tab');
    await a.click('.tnd-row [data-tndgo]');await sleep(250);
    t.is('Open tree goes to the project tree',!!await a.$(`[data-tn="${D.id}"]`));
    await a.hover(`[data-tn="${D.id}"]`);await a.click(`[data-tn="${D.id}"] [data-troff]`);await sleep(250);
    s=await state(a);let P=s.projects.find(x=>x.id===pid);
    t.is('Off tree takes it out and keeps it in Done',!P.tree.some(x=>x.id===D.id)&&P.treeDone.some(x=>x.id===D.id&&x.path==='Launch'));
    await a.click('[data-pback]');await sleep(200);await a.click('[data-view=done]');await sleep(250);
    t.is('off-tree node still in the Done section',await a.evaluate(()=>/Off the tree/.test(document.querySelector('.tnd-sec').textContent)));
    await a.click('.tnd-row [data-tndopen]');await sleep(250);
    s=await state(a);P=s.projects.find(x=>x.id===pid);
    t.is('unticking puts it back in the tree as open',P.tree.some(x=>x.id===D.id&&!x.done)&&!P.treeDone.length);
    await a.setViewportSize({width:390,height:800});await sleep(200);await shot(a,'tree-notes-390');await t.ok(a,'no sideways scroll at 390px',noSideScroll);
    t.is('no page errors',!errs.length);if(errs.length)console.log(errs.join('\n'));
  }catch(e){t.is('ran: '+String(e.message).split('\n').slice(0,2).join(' '),false)}
  await br.close();t.done()})();
